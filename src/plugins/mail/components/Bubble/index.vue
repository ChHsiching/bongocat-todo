<script setup lang="ts">
/**
 * Desktop-pet bubble (hand-drawn style, T2).
 *
 * Visuals strictly follow `docs/designs/phase2-exploration/bubble.html`: a chubby hand-drawn SVG shape
 * (never use CSS borders for the linework), a tail triangle hugging the pet's head and pointing at the cat, 851 font at font-weight 600 baseline.
 *
 * Mail and todo share this component (distinguished by the `type` prop), reserved for T6. This ticket only builds the mail bubble,
 * but the todo branch's content (title/subtitle copy, red-ink wave) is implemented as well so the prop structure stays stable.
 *
 * Interaction: clicking × closes; clicking the bubble body triggers `action` (mail→open webmail, todo→open the panel, decided by the parent),
 * both then trigger `close`. Pure fade in/out is controlled by the parent's fade class; this component only renders the static bubble.
 *
 * Shape adaptation: the SVG path is dynamically generated by `genBubbleShape(textHeight)` from the content's real height — when the content
 * wraps and grows taller, the bottom border and tail triangle follow it down, so text always stays inside the shape (fixes the user-reported
 * "content overflows outside the bubble" bug, caused by the original hard-coded path with bottom y≈66). Container height = viewBox height
 * (1:1, no stretching); the content is absolutely positioned at the correct spot inside the shape (symmetric top/bottom padding).
 *
 * @see docs/designs/phase2-exploration/bubble.html
 * @see ADR 0002 D7
 */
import { computed, ref, watch } from 'vue'
import { useI18n } from 'vue-i18n'

import { genBubbleShape } from '../../utils/bubbleShape'

/** Bubble type (prop, reserved for the T6 todo bubble). */
type BubbleType = 'mail' | 'todo'

const props = defineProps<{
  /** Bubble type: mail (envelope icon + pink wave) or todo (hand-drawn clock + red-ink wave). */
  type: BubbleType
  /** Source label (e.g. "New mail · Gmail" / "Todo due"). */
  source: string
  /** Main title (mail=sender; todo=task title). */
  title: string
  /** Subtitle (mail=subject; todo="Overdue · High priority"). */
  subtitle: string
  /** Whether the subtitle is highlighted (red ink for due todos). */
  urgent?: boolean
  /** Bubble width (px, decided by the parent from the max natural width of all bubbles, default 360). */
  width?: number
}>()

const emit = defineEmits<{
  /** Close the bubble (triggered by clicking ×, dismiss only, no jump). */
  close: []
  /** Click the bubble body (mail→open webmail; todo→open the panel); the parent will also close afterwards. */
  action: []
  /**
   * Content size changed (text wrapped / long link); the parent uses it to reset the window size.
   * payload = { height: text-only height, naturalWidth: the content's natural width (unconstrained, including padding) }.
   */
  resize: [height: number, naturalWidth: number]
}>()

const { t } = useI18n()

/** The SVG filter id must be unique within the window; a random suffix avoids clashes when multiple bubbles stack. */
const filterId = `b-sh-${Math.random().toString(36).slice(2, 8)}`

/**
 * Text-only height (px, excluding padding). Determined by a ResizeObserver measuring .bubble-content's
 * getBoundingClientRect().height (the content has no top/bottom padding, only left/right padding).
 * Initial 60 (a single-line estimate from the design), corrected to the real value by the observer after the first frame.
 */
const textHeight = ref(60)

/**
 * Content natural width (px, including left/right padding). Measured via scrollWidth, reflecting the real width of long links/long text that don't wrap.
 * The parent collects the naturalWidth of all bubbles and takes the max to decide the window width (≥360).
 */
const naturalWidth = ref(0)

/** Dynamically generate the shape from textHeight + width (path + viewBox + dimensions + contentTop). */
const shape = computed(() => genBubbleShape(textHeight.value, props.width))

/** Root element ref (the container, height set to shape.height). */
const rootEl = ref<HTMLElement | null>(null)

/** Content element ref (absolutely positioned, top = shape.contentTop). */
const contentEl = ref<HTMLElement | null>(null)

let ro: ResizeObserver | undefined

/**
 * Observe content size changes (text wrapped / long link), recompute the shape + notify the parent to resize the window.
 *
 * Measures two dimensions:
 * - height: text-only height (getBoundingClientRect().height), drives the SVG path height
 * - naturalWidth: the content's natural width (scrollWidth, including overflow). The parent takes the max across all bubbles to decide
 *   the window width, keeping long links from being squeezed or overflowing within the fixed 360.
 */
function measureContent() {
  const el = contentEl.value
  if (!el) {
    return
  }
  const h = Math.round(el.getBoundingClientRect().height)
  const nw = el.scrollWidth
  const hChanged = h > 0 && h !== textHeight.value
  const wChanged = nw > 0 && nw !== naturalWidth.value
  if (hChanged) {
    textHeight.value = h
  }
  if (wChanged) {
    naturalWidth.value = nw
  }
  if (hChanged || wChanged) {
    emit('resize', h, nw)
  }
}

watch(contentEl, (el) => {
  if (ro) {
    ro.disconnect()
  }
  if (!el) {
    return
  }
  ro = new ResizeObserver(() => measureContent())
  ro.observe(el)
  measureContent()
})
</script>

<template>
  <div
    ref="rootEl"
    class="bubble"
    :style="{ height: `${shape.height}px`, width: `${shape.width}px` }"
    @click="emit('action')"
  >
    <!-- Chubby hand-drawn bubble background (SVG path, never CSS border). The path is dynamically generated by genBubbleShape
         from text height + width. width/height = viewBox size (1:1, preserveAspectRatio="none" with no stretching). -->
    <svg
      class="bubble-bg"
      :height="shape.height"
      preserveAspectRatio="none"
      :viewBox="shape.viewBox"
      :width="shape.width"
    >
      <defs>
        <filter
          :id="filterId"
          height="135%"
          width="120%"
          x="-10%"
          y="-10%"
        >
          <feGaussianBlur
            in="SourceAlpha"
            stdDeviation="2.5"
          />
          <feOffset
            dx="1.5"
            dy="3"
          />
          <feComponentTransfer><feFuncA
            slope="0.12"
            type="linear"
          /></feComponentTransfer>
          <feMerge><feMergeNode /><feMergeNode in="SourceGraphic" /></feMerge>
        </filter>
      </defs>
      <!-- Paper shadow layer (offset hand-drawn shape, pale brown) -->
      <path
        :d="shape.shadowD"
        fill="var(--paper-shadow)"
        opacity="0.6"
      />
      <!-- Main bubble (pure white fill + hand-drawn chubby border + tail triangle pointing at the cat) -->
      <path
        :d="shape.mainD"
        fill="#fff"
        :filter="`url(#${filterId})`"
        stroke="var(--ink)"
        stroke-linecap="round"
        stroke-linejoin="round"
        stroke-width="2.5"
      />
      <!-- Top decorative hand-drawn wave: mail=pink, todo=red ink -->
      <path
        :d="shape.waveD"
        fill="none"
        opacity="0.6"
        :stroke="type === 'todo' ? 'var(--red-ink)' : 'var(--pink)'"
        stroke-linecap="round"
        stroke-width="1.8"
      />
    </svg>

    <!-- Content area: absolutely positioned inside the shape (top = shape.contentTop), symmetric top/bottom padding.
         No top/bottom padding (only left/right); height = text-only height, which drives the shape. -->
    <div
      ref="contentEl"
      class="bubble-content"
      :style="{ top: `${shape.contentTop}px` }"
    >
      <!-- Source icon round backdrop (mail=blue-toned envelope; todo=red-ink hand-drawn clock) -->
      <div
        class="source-icon"
        :class="type"
      >
        <template v-if="type === 'mail'">
          <svg
            fill="none"
            height="20"
            stroke="#5a85b0"
            stroke-linecap="round"
            stroke-linejoin="round"
            stroke-width="2"
            viewBox="0 0 24 24"
            width="20"
          >
            <rect
              height="13"
              rx="2.5"
              width="18"
              x="3"
              y="6"
            />
            <path d="M 4 8 Q 12 13 20 8" />
          </svg>
        </template>
        <template v-else>
          <svg
            fill="none"
            height="20"
            stroke="#d4654a"
            stroke-linecap="round"
            stroke-linejoin="round"
            stroke-width="2"
            viewBox="0 0 24 24"
            width="20"
          >
            <path d="M 12 2 Q 18 2 21 6 Q 23 9 22.5 13 Q 21.5 19 16 21 Q 12 22 8 21 Q 3 19 2.5 13.5 Q 2 9 4 6 Q 6 2 12 2 Z" />
            <path d="M 12 12 Q 12 8 13 6" />
            <path d="M 12 12 Q 16 12 18 11" />
            <circle
              cx="12"
              cy="12"
              fill="#d4654a"
              r="0.8"
              stroke="none"
            />
          </svg>
        </template>
      </div>

      <div class="bubble-body">
        <div class="bubble-source">
          {{ source }}
        </div>
        <div class="bubble-title">
          {{ title }}
        </div>
        <div
          class="bubble-subtitle"
          :class="{ urgent }"
        >
          {{ subtitle }}
        </div>
      </div>

      <!-- Hand-drawn × close (two crossing Q curves, not a CSS border) -->
      <button
        :aria-label="t('plugins.mail.labels.bubbleClose')"
        class="bubble-close"
        type="button"
        @click.stop="emit('close')"
      >
        <svg
          fill="none"
          height="18"
          stroke="currentColor"
          stroke-linecap="round"
          stroke-width="2.5"
          viewBox="0 0 24 24"
          width="18"
        >
          <!-- Hand-drawn ×: two smooth large crossing arcs, consistent with the todo panel -->
          <path d="M 6 6 Q 9.5 13 19 19" />
          <path d="M 18 6 Q 8.5 10 5 18" />
        </svg>
      </button>
    </div>
  </div>
</template>

